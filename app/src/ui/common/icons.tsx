export type IconName = keyof typeof ICONS;

const cache = new Map<string, { main: string; hi: string; lo: string }>();

function build(name: IconName) {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = ICONS[name];
  let main = '', hi = '', lo = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      const r = `M${x} ${y}h1v1h-1z`;
      if (c === '#') main += r; else if (c === '+') hi += r; else if (c === '-') lo += r;
    }
  });
  const out = { main, hi, lo };
  cache.set(name, out);
  return out;
}

export function Icon({ name, size, class: cls = '', title }: { name: IconName; size?: 'sm' | 'lg' | 'xl'; class?: string; title?: string }) {
  const p = build(name);
  return (
    <svg class={`ico ${size ?? ''} ${cls}`} viewBox="0 0 12 12" aria-hidden={title ? undefined : 'true'} role={title ? 'img' : undefined}>
      {title && <title>{title}</title>}
      {p.lo && <path d={p.lo} fill="currentColor" opacity="0.28" />}
      <path d={p.main} fill="currentColor" />
      {p.hi && <path d={p.hi} fill="#fff" opacity="0.85" />}
    </svg>
  );
}

export const iconNames = Object.keys(ICONS) as IconName[];
