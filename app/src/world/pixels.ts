let atlas: THREE.CanvasTexture | null = null;
export function particleAtlas(): THREE.CanvasTexture {
  if (atlas) return atlas;
  atlas = pixTex(128, 64, (ctx) => {
    for (const [name, rows] of Object.entries(ART) as [TileName, string[]][]) {
      const t = TILE[name]; const tx = (t % 8) * 16, ty = Math.floor(t / 8) * 16;
      const oy = Math.floor((16 - rows.length) / 2);
      rows.forEach((row, j) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') { ctx.fillStyle = '#fff'; ctx.fillRect(tx + i, ty + oy + j, 1, 1); } });
    }
  });
  atlas.flipY = false;
  return atlas;
}
