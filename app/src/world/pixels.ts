export const glyph = (ch: string) => F[ch] ?? F[ch.toUpperCase()] ?? F['?'];

/** Draw pixel text; returns width in px. */
export function pixText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale = 1, color = '#9dff8a', spacing = 1): number {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    for (let row = 0; row < 7; row++) for (let col = 0; col < 5; col++)
      if (g[row] & (1 << (4 - col))) ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
    cx += (5 + spacing) * scale;
  }
  return cx - x;
}
export const pixTextWidth = (text: string, scale = 1, spacing = 1) => [...text].length * (5 + spacing) * scale - spacing * scale;

// ── canvas textures ──────────────────────────────────────────────────────────
export function canvas(w: number, h: number) {
  const c = document.createElement('canvas'); c.width = w; c.height = h;
  const ctx = c.getContext('2d')!; ctx.imageSmoothingEnabled = false;
  return { c, ctx };
}

export function pixTex(w: number, h: number, draw: (ctx: CanvasRenderingContext2D, w: number, h: number) => void, smooth = false): THREE.CanvasTexture {
  const { c, ctx } = canvas(w, h);
  draw(ctx, w, h);
  const t = new THREE.CanvasTexture(c);
  t.colorSpace = THREE.SRGBColorSpace;
  t.magFilter = smooth ? THREE.LinearFilter : THREE.NearestFilter;
  t.minFilter = smooth ? THREE.LinearMipmapLinearFilter : THREE.NearestFilter;
  t.generateMipmaps = smooth;
  return t;
}

/** Draw a pixel-stepped filled ellipse. */
export function pixEllipse(ctx: CanvasRenderingContext2D, cx: number, cy: number, rx: number, ry: number, color: string) {
  ctx.fillStyle = color;
  for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++)
    for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) {
      const dx = (x + 0.5 - cx) / rx, dy = (y + 0.5 - cy) / ry;
      if (dx * dx + dy * dy <= 1) ctx.fillRect(x, y, 1, 1);
    }
}

/** Draw a sprite from string rows using a palette. */
export function pixArt(ctx: CanvasRenderingContext2D, rows: string[], x: number, y: number, pal: Record<string, string>, scale = 1) {
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const col = pal[row[i]];
      if (!col) continue;
      ctx.fillStyle = col; ctx.fillRect(x + i * scale, y + j * scale, scale, scale);
    }
  });
}

